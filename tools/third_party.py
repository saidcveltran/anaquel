"""Writes THIRD-PARTY.md: the crates Anaquel is built from, with version and licence.

Run from the repository root:  python -I tools/third_party.py [--check]

`--check` exits 1 when the file is out of date, so CI can keep it honest. The list is what
`cargo tree` reports for the `anaquel` program, normal and build dependencies, for every target;
crates of this workspace are left out. The section on bundled programs and fonts is kept as it is.
"""
import datetime
import difflib
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "THIRD-PARTY.md"
MARK = "## Programs bundled with a release"
HEAD = """# Third-party software

Anaquel is built from the Rust crates below. Each is used under the licence
shown; the full text is in the crate's own package. Generated by
`tools/third_party.py` from `cargo tree`.

| Crate | Version | Licence |
| --- | --- | --- |
"""


def crates():
    out = subprocess.run(
        [
            "cargo", "tree", "--locked", "-p", "anaquel", "--edges", "no-dev", "--all-features",
            "--target", "all", "--prefix", "none", "--format", "{p}|{l}",
        ],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True,
    ).stdout
    found = {}
    for line in out.splitlines():
        line = line.strip()
        if not line or line.endswith("(*)") and "|" not in line:
            continue
        package, _, licence = line.partition("|")
        package = package.replace(" (proc-macro)", "")
        if "(" in package:  # a crate of this workspace: `name vX (path)`
            continue
        licence = licence.replace(" (*)", "").strip()
        name, _, version = package.replace(" (*)", "").partition(" v")
        found[(name, version)] = licence or "UNKNOWN"
    return sorted(found.items())


def render(tail):
    rows = "".join(f"| {n} | {v} | {lic} |\n" for (n, v), lic in crates())
    return HEAD + rows + "\n" + tail


def main():
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    tail = old[old.index(MARK):] if MARK in old else MARK + "\n"
    new = render(tail)
    if "--check" in sys.argv:
        if new.replace("\r\n", "\n") != old.replace("\r\n", "\n"):
            sys.stdout.write("THIRD-PARTY.md is out of date; run: python -I tools/third_party.py\n")
            shown = difflib.unified_diff(
                old.replace("\r\n", "\n").splitlines(), new.replace("\r\n", "\n").splitlines(),
                "committed", "generated", lineterm="", n=0,
            )
            sys.stdout.write("\n".join(list(shown)[:40]) + "\n")
            return 1
        return 0
    TARGET.write_text(new, encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {TARGET.name} on {datetime.date.today()}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
